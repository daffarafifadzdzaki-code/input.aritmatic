a = input("Masukkan angka pertama: ")
b = input("Masukkan angka kedua: ")

print(a, ' + ', b, ' = ', int(a) + int(b))
print(a, ' - ', b, ' = ', int(a) - int(b))
print(a, ' * ', b, ' = ', int(a) * int(b))
print(a, ' / ', b, ' = ', int(a) / int(b))
print(a, ' % ', b, ' = ', int(a) % int(b))
print(a, ' // ', b, ' = ', int(a) // int(b))
print(a, ' ** ', b, ' = ', int(a) ** int(b))
